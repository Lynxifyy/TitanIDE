package dev.titanide.core.templates

import dev.titanide.core.model.Language

/** Shared helpers so every generator produces consistent, valid identifiers and files. */
internal object Gen {

    fun pathOf(packageName: String): String = packageName.replace('.', '/')

    fun appClassName(projectName: String): String =
        projectName.split(Regex("[^A-Za-z0-9]+"))
            .filter { it.isNotBlank() }
            .joinToString("") { it.replaceFirstChar(Char::uppercaseChar) }
            .ifBlank { "App" }
            .let { if (it.first().isDigit()) "App$it" else it }

    fun sanitizePackage(packageName: String): String {
        val parts = packageName.split('.').filter { it.isNotBlank() }
        if (parts.isEmpty()) return "dev.titanide.app"
        return parts.joinToString(".") { segment ->
            val cleaned = segment.filter { it.isLetterOrDigit() || it == '_' }
            when {
                cleaned.isEmpty() -> "app"
                cleaned.first().isDigit() -> "_$cleaned"
                else -> cleaned
            }
        }
    }

    /** Root Gradle build for an Android project, kept in one place so versions never drift. */
    fun androidRootBuild(): String = """
        plugins {
            id("com.android.application") version "8.13.2" apply false
            id("com.android.library") version "8.13.2" apply false
            id("org.jetbrains.kotlin.android") version "2.2.21" apply false
            id("org.jetbrains.kotlin.plugin.compose") version "2.2.21" apply false
        }
    """.trimIndent() + "\n"

    fun androidSettings(projectName: String): String = """
        pluginManagement {
            repositories {
                google()
                mavenCentral()
                gradlePluginPortal()
            }
        }
        dependencyResolutionManagement {
            repositoriesMode.set(RepositoriesMode.FAIL_ON_PROJECT_REPOS)
            repositories {
                google()
                mavenCentral()
            }
        }

        rootProject.name = "$projectName"
        include(":app")
    """.trimIndent() + "\n"

    fun gradleProperties(): String = """
        org.gradle.jvmargs=-Xmx2048m -Dfile.encoding=UTF-8
        org.gradle.parallel=true
        org.gradle.caching=true
        android.useAndroidX=true
        android.nonTransitiveRClass=true
        kotlin.code.style=official
    """.trimIndent() + "\n"

    fun androidManifest(applicationClass: String?, label: String, theme: String? = null): String {
        val appName = if (applicationClass != null) "android:name=\".$applicationClass\"" else ""
        val themeAttr = if (theme != null) "\n        android:theme=\"@style/$theme\"" else ""
        return """
            <?xml version="1.0" encoding="utf-8"?>
            <manifest xmlns:android="http://schemas.android.com/apk/res/android">

                <application
                    $appName
                    android:allowBackup="true"
                    android:label="$label"
                    android:supportsRtl="true"$themeAttr>
                    <activity
                        android:name=".MainActivity"
                        android:exported="true">
                        <intent-filter>
                            <action android:name="android.intent.action.MAIN" />
                            <category android:name="android.intent.category.LAUNCHER" />
                        </intent-filter>
                    </activity>
                </application>

            </manifest>
        """.trimIndent() + "\n"
    }

    fun stringsXml(appName: String): String = """
        <?xml version="1.0" encoding="utf-8"?>
        <resources>
            <string name="app_name">$appName</string>
        </resources>
    """.trimIndent() + "\n"

    fun gitignore(): String = """
        *.iml
        .gradle
        /local.properties
        .idea
        .DS_Store
        build/
        captures/
        .cxx/
        node_modules/
        __pycache__/
        target/
        .venv/
        dist/
    """.trimIndent() + "\n"

    fun readme(projectName: String, description: String, buildCommand: String?, runCommand: String?): String {
        val build = if (buildCommand != null) "\n## Build\n\n```\n$buildCommand\n```\n" else ""
        val run = if (runCommand != null) "\n## Run\n\n```\n$runCommand\n```\n" else ""
        return """
            # $projectName

            $description

            Generated by TITAN IDE.
            $build$run
        """.trimIndent() + "\n"
    }

    fun languageForFile(path: String): Language = Language.fromFileName(path)
}
